// build-skill.mjs — one source of truth for the gated kernel, the live page and the Agensi skill script.
//
// kernel.mjs is the source (tested + witness-gated). make-page.mjs injects it into index.html; this script
// inlines the SAME text (exports stripped, exactly as make-page.mjs strips them) with cli.mjs into
// scripts/claim-receipt-gate.mjs — one file, because Agensi runs a script alone from a temp file.
//
//   node build-skill.mjs           write scripts/claim-receipt-gate.mjs
//   node build-skill.mjs --check   exit 1 if the script or the page's kernel block drifted (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const NAME = JSON.parse(readFileSync('package.json', 'utf8')).name;
const OUT = `scripts/${NAME}.mjs`;

export function pageKernel(src) {
  return src.replace(/^export default .*;?\s*$/gm, '').replace(/^export /gm, '').replace(/\r\n/g, '\n').trimEnd();
}

export function skillScript(kernel, cli) {
  const body = cli.replace(/\r\n/g, '\n').split('\n').filter((l) => !/^import .* from '\.\/kernel\.mjs';\s*$/.test(l)).join('\n');
  return '#!/usr/bin/env node\n' +
    `// ${NAME} — Agensi skill script, generated by build-skill.mjs in the sjgant80-hub/post-proof repository.\n` +
    '// The KERNEL below is the same text the live page runs and that kernel.mjs exports, which the tests and\n' +
    '// the witness mutation gate run against. No network, no dependencies, writes no files: it reads the\n' +
    '// input you name and prints a JSON report to stdout. MIT licence.\n' +
    '// ---- KERNEL (from kernel.mjs) ----\n' + kernel + '\n' +
    '// ---- CLI (from cli.mjs) ----\n' + body;
}

const kernel = pageKernel(readFileSync('kernel.mjs', 'utf8'));
const want = skillScript(kernel, readFileSync('cli.mjs', 'utf8'));

if (process.argv.includes('--check')) {
  let drift = 0;
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (have !== want) { console.error(`✗ ${OUT} is out of date: run node build-skill.mjs`); drift++; }
  else console.log(`✓ ${OUT} = kernel.mjs + cli.mjs`);
  const page = readFileSync('index.html', 'utf8').replace(/\r\n/g, '\n');
  const BEGIN = '// ⟦KERNEL-BEGIN⟧ generated from kernel.mjs by make-page.mjs — do not edit here\n';
  const a = page.indexOf(BEGIN), b = page.indexOf('\n// ⟦KERNEL-END⟧');
  if (a === -1 || b === -1 || page.slice(a + BEGIN.length, b) !== kernel) { console.error('✗ index.html kernel block differs from kernel.mjs: run node make-page.mjs'); drift++; }
  else console.log('✓ index.html runs the same kernel');
  process.exit(drift ? 1 : 0);
}
mkdirSync('scripts', { recursive: true });
writeFileSync(OUT, want);
console.log(`wrote ${OUT} (${Buffer.byteLength(want)} bytes)`);
